import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const string = { type: 'string' };
const strings = { type: 'array', items: string };
const cells = { type: 'array', items: strings };
const object = properties => ({ type: 'object', properties, required: Object.keys(properties), additionalProperties: false });
const part = object({ Id: string, Prompt: string, Type: { type: 'string', enum: ['text', 'table'] }, Points: { type: 'number' }, ExpectedAnswer: string, Columns: strings, Rows: strings, CorrectCells: cells });
const parts = { type: 'array', items: part };
const issueFields = { FileName: string, Explanation: string, Impact: string, Recommendation: string };
const examFile = path.join(root, 'Schemas', 'exam.json');
const exam = JSON.parse(fs.readFileSync(examFile, 'utf8'));
Object.assign(exam.properties, { IsQuiz: { type: 'boolean' }, SourceQuestionCount: { type: 'integer' }, PresentationVersion: { type: 'integer' }, SourceIssues: { type: 'array', items: object(issueFields) } });
exam.required = Object.keys(exam.properties);
const question = exam.properties.Questions.items;
Object.assign(question.properties, { Context: string, Parts: parts, ImageIds: strings, SourceUnitIds: strings });
question.required = Object.keys(question.properties);
fs.writeFileSync(examFile, JSON.stringify(exam, null, 2) + '\n');
const presentation = object({ Questions: { type: 'array', items: object({ QuestionId: string, Context: string, Hint: string, Parts: parts }) } });
fs.writeFileSync(path.join(root, 'Schemas', 'presentation.json'), JSON.stringify(presentation, null, 2) + '\n');
const materials = object({ Summary: string, Files: { type: 'array', items: object({ ...issueFields, Status: { type: 'string', enum: ['read', 'partial', 'unread'] } }) } });
fs.writeFileSync(path.join(root, 'Schemas', 'materials.json'), JSON.stringify(materials, null, 2) + '\n');
const visuals = object({ Items: { type: 'array', items: object({ Id: string, Status: { type: 'string', enum: ['read', 'partial', 'unread'] }, Text: string, Description: string, Caption: string, Issue: string, ExamSuitable: { type: 'boolean' } }) } });
fs.writeFileSync(path.join(root, 'Schemas', 'visuals.json'), JSON.stringify(visuals, null, 2) + '\n');
